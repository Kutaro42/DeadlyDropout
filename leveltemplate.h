// ═══════════════════════════════════════════════════════════════════
//  SYSTÈME DE TEMPLATE DE NIVEAU — VERSION 2 (matrices séparées)
//
//  Chaque niveau est défini par DEUX matrices de même dimension :
//
//  entityMatrix  (ancienne matrice unique, sans les murs) :
//    0 = FLOOR        (sol libre)
//    2 = ZOMBIE_SPAWN
//    3 = EXIT_DOOR
//    4 = PLAYER_SPAWN
//
//  wallMatrix (nouvelle) :
//    0 = pas de mur
//    N = index de tile dans le tileset (1-based)
//
//  Le LevelDescriptor transporte les deux flat-arrays + tilesetCols
//  pour que WallView puisse découper le bon sprite.
// ═══════════════════════════════════════════════════════════════════

template<int ROWS, int COLS>
struct LevelMatrix {
    static constexpr int rows = ROWS;
    static constexpr int cols = COLS;
    int data[ROWS][COLS];
    int at(int r, int c) const { return data[r][c]; }
};

// ─── Descripteur "type-erased" ────────────────────────────────────
struct LevelDescriptor {
    int         id;
    QString     name;
    int         rows;
    int         cols;

    const int*  entityData;   ///< Matrice entités (spawns, sortie…)
    const int*  wallData;     ///< Matrice murs  (0 = vide, N = index tileset)
    int         tilesetCols;  ///< Nombre de colonnes du tileset PNG

    int entityAt(int r, int c) const { return entityData[r * cols + c]; }
    int wallAt  (int r, int c) const { return wallData  [r * cols + c]; }
};

// ─── Helper ───────────────────────────────────────────────────────
template<int ROWS, int COLS>
inline LevelDescriptor makeDescriptor(int id, const QString& name,
                                      const LevelMatrix<ROWS, COLS>& entities,
                                      const LevelMatrix<ROWS, COLS>& walls,
                                      int tilesetCols = 8)
{
    return { id, name, ROWS, COLS,
            &entities.data[0][0],
            &walls.data[0][0],
            tilesetCols };
}

